"""Translate IAM roles and permissions into Argo CD RBAC policy (policy.csv).

The output can be placed in the ``argocd-rbac-cm`` ConfigMap so that Argo CD
itself enforces the same model when users reach it directly. Production
applications are identified by the ``-prod`` name suffix convention because
Argo CD policies match ``<project>/<application>`` globs.
"""

from __future__ import annotations

from typing import List, Tuple

from argo_iam.authorization.permissions import ARGOCD_PERMISSIONS, Permission
from argo_iam.users.models import Role

PRODUCTION_GLOB = "*/*-prod"

# permission -> list of (resource, action, object, effect)
_TRANSLATION = {
    Permission.APP_VIEW: [("applications", "get", "*/*", "allow")],
    Permission.APP_REFRESH: [("applications", "get", "*/*", "allow")],
    Permission.APP_SYNC: [("applications", "sync", "*/*", "allow")],
    Permission.APP_SYNC_PRODUCTION: [("applications", "sync", PRODUCTION_GLOB, "allow")],
    Permission.PROJECT_VIEW: [("projects", "get", "*", "allow")],
    Permission.PROJECT_UPDATE: [("projects", "update", "*", "allow")],
}


def argocd_role_name(role: Role) -> str:
    return f"role:iam-{role.value}"


def policy_rules(role: Role) -> List[Tuple[str, str, str, str]]:
    perms = ARGOCD_PERMISSIONS[role]
    rules = []
    for perm in sorted(perms, key=lambda p: p.value):
        for rule in _TRANSLATION.get(perm, []):
            if rule not in rules:
                rules.append(rule)
    # Operators may sync everything except production; Argo CD deny rules win.
    if Permission.APP_SYNC in perms and Permission.APP_SYNC_PRODUCTION not in perms:
        rules.append(("applications", "sync", PRODUCTION_GLOB, "deny"))
    return rules


def render_policy_csv(group_prefix: str = "argo-iam") -> str:
    lines = [
        "# Generated by the Argo IAM Governance Layer.",
        "# Place under data.policy.csv in the argocd-rbac-cm ConfigMap.",
    ]
    for role in Role:
        lines.append(f"# {role.label}")
        subject = argocd_role_name(role)
        for resource, action, obj, effect in policy_rules(role):
            lines.append(f"p, {subject}, {resource}, {action}, {obj}, {effect}")
    lines.append("# SSO groups emitted by the IAM layer -> Argo CD roles")
    for role in Role:
        lines.append(f"g, {group_prefix}-{role.value}s, {argocd_role_name(role)}")
    return "\n".join(lines) + "\n"
